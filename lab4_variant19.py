import bisect  # стандартный модуль двоичного поиска (нужен для задания Б5)
import platform  # сведения о компьютере для раздела отчёта «Характеристики системы»
import random  # генерация случайных запросов
import time  # измерение времени работы
import matplotlib.pyplot as plt  # построение графиков

SIZES = [10**4, 10**5, 10**6]  # размеры массива n по варианту 19
K = 1000  # число запросов k по варианту 19 (все запросы успешные)
C, D = 5, 7  # параметры арифметической прогрессии A[i] = C + D * i (распределение «А»)


def linear_search(a, q):  # последовательный поиск: массив a, ключ q
    for i, v in enumerate(a):  # перебираем элементы по порядку вместе с их индексами
        if v == q:  # сравниваем текущий элемент с ключом
            return i, i + 1  # нашли: возвращаем индекс и число сравнений (оно равно i + 1)
    return -1, len(a)  # не нашли: индекс -1, выполнено n сравнений


def binary_search(a, q):  # двоичный поиск (массив должен быть упорядочен)
    lo, hi, cmps = 0, len(a) - 1, 0  # левая и правая границы отрезка, счётчик сравнений
    while lo <= hi:  # пока отрезок поиска не пуст
        mid = lo + (hi - lo) // 2  # берём середину отрезка (безопасная форма)
        cmps += 1  # считаем сравнение a[mid] с ключом
        if a[mid] == q:  # ключ найден в середине
            return mid, cmps  # возвращаем индекс и число сравнений
        if a[mid] < q:  # середина меньше ключа, значит ключ справа
            lo = mid + 1  # отбрасываем левую половину
        else:  # середина больше ключа, значит ключ слева
            hi = mid - 1  # отбрасываем правую половину
    return -1, cmps  # отрезок опустел, ключа нет


def interpolation_search(a, q):  # интерполяционный поиск (массив упорядочен)
    lo, hi, cmps = 0, len(a) - 1, 0  # границы отрезка и счётчик сравнений
    while lo <= hi and a[lo] <= q <= a[hi]:  # ключ должен лежать в диапазоне значений отрезка
        if a[lo] == a[hi]:  # все значения на отрезке одинаковы, делить на ноль нельзя
            cmps += 1  # одно сравнение с единственным значением
            return (lo, cmps) if a[lo] == q else (-1, cmps)  # нашли или нет
        mid = lo + (q - a[lo]) * (hi - lo) // (a[hi] - a[lo])  # ожидаемая позиция ключа
        cmps += 1  # считаем сравнение a[mid] с ключом
        if a[mid] == q:  # угадали позицию
            return mid, cmps  # возвращаем индекс и число сравнений
        if a[mid] < q:  # ключ правее ожидаемой позиции
            lo = mid + 1  # сдвигаем левую границу
        else:  # ключ левее ожидаемой позиции
            hi = mid - 1  # сдвигаем правую границу
    return -1, cmps  # ключ вне диапазона или не найден


def bisect_search(a, q):  # поиск через стандартный модуль bisect (задание Б5)
    i = bisect.bisect_left(a, q)  # индекс первого элемента, который не меньше q (код на языке C)
    return (i, 0) if i < len(a) and a[i] == q else (-1, 0)  # проверяем совпадение; сравнения не считаем


def make_data(n):  # генерация массива по варианту: арифметическая прогрессия
    return [C + D * i for i in range(n)]  # A[i] = C + D * i, массив сразу упорядочен


def benchmark(func, data, queries):  # замер среднего времени и среднего числа сравнений
    for q in queries[:20]:  # проверка правильности на первых 20 запросах
        assert data[func(data, q)[0]] == q  # найденный индекс должен указывать на ключ
    total = 0  # сумма сравнений по всем запросам
    start = time.perf_counter()  # засекаем время начала серии запросов
    for q in queries:  # выполняем все запросы подряд
        total += func(data, q)[1]  # прибавляем число сравнений текущего запроса
    elapsed = time.perf_counter() - start  # общее время серии
    return elapsed / len(queries), total / len(queries)  # среднее время одного запроса и среднее число сравнений


if __name__ == "__main__":  # запуск только при прямом старте файла
    print(platform.platform(), "|", platform.processor() or platform.machine(), "| Python", platform.python_version())  # система
    algos = {"Последовательный": linear_search, "Двоичный": binary_search,  # словарь алгоритмов: имя -> функция
             "Интерполяционный": interpolation_search, "bisect": bisect_search}  # bisect добавлен для Б5
    times = {name: [] for name in algos}  # сюда сложим время (мкс) по каждому n
    cmps = {name: [] for name in algos}  # сюда сложим число сравнений по каждому n
    rng = random.Random(1)  # генератор с фиксированным seed, чтобы результаты повторялись
    for n in SIZES:  # перебираем размеры массива
        data = make_data(n)  # строим массив из n элементов
        queries = [rng.choice(data) for _ in range(K)]  # K успешных запросов: случайные элементы массива
        print(f"\nn = {n}")  # заголовок блока результатов
        for name, func in algos.items():  # запускаем каждый алгоритм на одних и тех же запросах
            t, c = benchmark(func, data, queries)  # получаем среднее время и среднее число сравнений
            times[name].append(t * 1e6)  # переводим секунды в микросекунды и сохраняем
            cmps[name].append(c)  # сохраняем среднее число сравнений
            print(f"  {name:<18}{t * 1e6:>12.3f} мкс{c:>14.1f} сравнений")  # печатаем строку результата
    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(12, 4.5))  # два графика рядом
    for name in algos:  # рисуем линию для каждого алгоритма
        ax1.plot(SIZES, times[name], "o-", label=name)  # график времени от n
        if name != "bisect":  # у bisect число сравнений неизвестно, его не рисуем
            ax2.plot(SIZES, cmps[name], "o-", label=name)  # график числа сравнений от n
    for ax, title in ((ax1, "Среднее время запроса, мкс"), (ax2, "Среднее число сравнений")):  # оформление осей
        ax.set_xscale("log")  # логарифмическая шкала по оси n (требование задания)
        ax.set_yscale("log")  # логарифмическая шкала по оси y, т.к. значения различаются в тысячи раз
        ax.set_xlabel("n")  # подпись оси абсцисс
        ax.set_title(title)  # заголовок графика
        ax.grid(True, which="both", alpha=0.3)  # сетка для удобства чтения
        ax.legend()  # легенда с названиями алгоритмов
    plt.tight_layout()  # убираем наложение подписей
    plt.savefig("lab4_graphs.png", dpi=150)  # сохраняем график в файл для отчёта
    plt.show()  # показываем график на экране
